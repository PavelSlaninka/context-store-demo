"""Copy a store into the app as app/js/data.js, so the app runs offline from file://.

The app can't fetch JSON over file://, so the store is written as a small script
that sets window.DEMO_STORE. By default it exports the pristine seed (store/seed/).

Run from demo/:  .venv/bin/python -I tools/export_app_data.py [--store store]
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

DEMO = Path(__file__).resolve().parents[1]


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--store", default=str(DEMO / "store" / "seed"), help="store folder to export")
    args = ap.parse_args()
    folder = Path(args.store)
    data = {}
    for name in ("entries", "proposals", "history", "connectors", "reads"):
        data[name] = json.loads((folder / f"{name}.json").read_text(encoding="utf-8"))
    out = DEMO / "app" / "js" / "data.js"
    body = json.dumps(data, indent=1, ensure_ascii=True)
    out.write_text(
        "/* Generated by tools/export_app_data.py from " + folder.name + "/. Do not edit by hand. */\n"
        "window.DEMO_STORE = " + body + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {out} ({out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
